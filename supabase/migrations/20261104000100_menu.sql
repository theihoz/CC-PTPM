-- ── Hàm dùng chung: tự cập nhật cột updated_at ──────────────────────────────
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- ── categories: danh mục món ────────────────────────────────────────────────
create table if not exists public.categories (
  id          smallint generated by default as identity primary key,
  slug        text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name        text not null check (length(trim(name)) > 0),
  icon        text not null default '🍽️',
  sort_order  smallint not null default 0
);

comment on table public.categories is 'Danh mục món ăn (Bún & Phở, Cơm, Đồ uống…).';

-- ── restaurants: quán ăn ────────────────────────────────────────────────────
create table if not exists public.restaurants (
  id                 bigint generated by default as identity primary key,
  slug               text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name               text not null check (length(trim(name)) > 0),
  description        text not null default '',
  image_url          text,
  address            text not null default '',
  category_id        smallint references public.categories (id) on delete set null,
  rating             numeric(2, 1) not null default 0 check (rating between 0 and 5),
  rating_count       integer not null default 0 check (rating_count >= 0),
  delivery_time_min  smallint not null default 30 check (delivery_time_min > 0),
  open_time          time not null default '07:00',
  close_time         time not null default '22:00',
  is_featured        boolean not null default false,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

comment on table public.restaurants is 'Quán ăn. category_id là danh mục chính để hiển thị.';
comment on column public.restaurants.close_time is 'Nhỏ hơn open_time nghĩa là quán mở qua nửa đêm.';

-- ── foods: món ăn ───────────────────────────────────────────────────────────
create table if not exists public.foods (
  id            bigint generated by default as identity primary key,
  restaurant_id bigint not null references public.restaurants (id) on delete cascade,
  category_id   smallint references public.categories (id) on delete set null,
  name          text not null check (length(trim(name)) > 0),
  description   text not null default '',
  image_url     text,
  base_price    integer not null check (base_price >= 0),
  calories      integer not null default 0 check (calories >= 0),
  tags          text[] not null default '{}',
  stock         integer not null default 0 check (stock >= 0),
  has_spice     boolean not null default false,
  is_featured   boolean not null default false,
  is_available  boolean not null default true,
  sort_order    smallint not null default 0,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

comment on table public.foods is 'Món ăn của một quán. stock là tồn kho theo món (không tách theo size).';
comment on column public.foods.tags is 'Tag khẩu vị dùng cho lọc và AI gợi ý: cay, chay, it-calo, giau-dam, no-lau, nhe-bung, ngot, mat-lanh.';
comment on column public.foods.has_spice is 'true thì khách được chọn độ cay 0–4.';
comment on column public.foods.is_available is 'false thì ẩn món khỏi thực đơn (khác với hết hàng: stock = 0).';

-- ── food_sizes: size của món, có phụ thu ────────────────────────────────────
create table if not exists public.food_sizes (
  id           bigint generated by default as identity primary key,
  food_id      bigint not null references public.foods (id) on delete cascade,
  name         text not null check (length(trim(name)) > 0),
  price_delta  integer not null default 0 check (price_delta >= 0),
  is_default   boolean not null default false,
  sort_order   smallint not null default 0,
  unique (food_id, name)
);

-- Mỗi món có tối đa một size mặc định.
create unique index if not exists food_sizes_one_default_per_food
  on public.food_sizes (food_id) where is_default;

-- ── food_toppings: topping của món, có giá ──────────────────────────────────
create table if not exists public.food_toppings (
  id          bigint generated by default as identity primary key,
  food_id     bigint not null references public.foods (id) on delete cascade,
  name        text not null check (length(trim(name)) > 0),
  price       integer not null default 0 check (price >= 0),
  sort_order  smallint not null default 0,
  unique (food_id, name)
);

-- ── Index cho các cột hay tìm, lọc, join ────────────────────────────────────
create index if not exists restaurants_category_id_idx on public.restaurants (category_id);
create index if not exists restaurants_featured_idx    on public.restaurants (is_featured) where is_featured;
create index if not exists foods_restaurant_id_idx     on public.foods (restaurant_id);
create index if not exists foods_category_id_idx       on public.foods (category_id);
create index if not exists foods_featured_idx          on public.foods (is_featured) where is_featured;
create index if not exists foods_tags_idx              on public.foods using gin (tags);
create index if not exists food_sizes_food_id_idx      on public.food_sizes (food_id);
create index if not exists food_toppings_food_id_idx   on public.food_toppings (food_id);

-- ── Trigger updated_at ──────────────────────────────────────────────────────
drop trigger if exists restaurants_set_updated_at on public.restaurants;
create trigger restaurants_set_updated_at
  before update on public.restaurants
  for each row execute function public.set_updated_at();

drop trigger if exists foods_set_updated_at on public.foods;
create trigger foods_set_updated_at
  before update on public.foods
  for each row execute function public.set_updated_at();

-- ── Row Level Security: ai cũng đọc được thực đơn, không ai ghi từ client ──
alter table public.categories    enable row level security;
alter table public.restaurants   enable row level security;
alter table public.foods         enable row level security;
alter table public.food_sizes    enable row level security;
alter table public.food_toppings enable row level security;

drop policy if exists "Menu: ai cũng đọc được" on public.categories;
create policy "Menu: ai cũng đọc được" on public.categories
  for select to anon, authenticated using (true);

drop policy if exists "Menu: ai cũng đọc được" on public.restaurants;
create policy "Menu: ai cũng đọc được" on public.restaurants
  for select to anon, authenticated using (true);

drop policy if exists "Menu: ai cũng đọc được món đang bán" on public.foods;
create policy "Menu: ai cũng đọc được món đang bán" on public.foods
  for select to anon, authenticated using (is_available);

drop policy if exists "Menu: ai cũng đọc được" on public.food_sizes;
create policy "Menu: ai cũng đọc được" on public.food_sizes
  for select to anon, authenticated using (true);

drop policy if exists "Menu: ai cũng đọc được" on public.food_toppings;
create policy "Menu: ai cũng đọc được" on public.food_toppings
  for select to anon, authenticated using (true);

-- Không có policy INSERT/UPDATE/DELETE nên RLS đã chặn ghi.
-- Thu hồi thêm quyền ghi ở mức bảng để chặn hai lớp.
revoke insert, update, delete, truncate on
  public.categories, public.restaurants, public.foods, public.food_sizes, public.food_toppings
  from anon, authenticated;
