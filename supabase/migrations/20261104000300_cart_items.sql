-- topping_ids phải tăng dần và không trùng, để cùng một bộ topping chỉ có một cách ghi.
create or replace function public.is_sorted_unique(ids bigint[])
returns boolean
language sql
immutable
parallel safe
set search_path = ''
as $$
  select coalesce(
    (select bool_and(ids[i] < ids[i + 1]) from generate_subscripts(ids, 1) as i
     where i < array_upper(ids, 1)),
    true
  );
$$;

create table if not exists public.cart_items (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null default auth.uid() references auth.users (id) on delete cascade,
  food_id      bigint not null references public.foods (id) on delete cascade,
  size_id      bigint references public.food_sizes (id) on delete cascade,
  topping_ids  bigint[] not null default '{}' check (public.is_sorted_unique(topping_ids)),
  spice_level  smallint not null default 0 check (spice_level between 0 and 4),
  quantity     integer not null check (quantity between 1 and 99),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  -- Một lựa chọn chỉ có một dòng; size_id null cũng tính là trùng nhau.
  constraint cart_items_line_unique
    unique nulls not distinct (user_id, food_id, size_id, spice_level, topping_ids)
);

comment on table public.cart_items is 'Giỏ hàng của người đã đăng nhập. Khách vãng lai dùng LocalStorage.';
comment on column public.cart_items.topping_ids is 'Id topping tăng dần, không trùng. Rỗng nếu không chọn topping.';

create index if not exists cart_items_user_id_idx on public.cart_items (user_id);
create index if not exists cart_items_food_id_idx on public.cart_items (food_id);
create index if not exists cart_items_size_id_idx on public.cart_items (size_id);

drop trigger if exists cart_items_set_updated_at on public.cart_items;
create trigger cart_items_set_updated_at
  before update on public.cart_items
  for each row execute function public.set_updated_at();

-- ── Row Level Security: mỗi người chỉ thấy và sửa giỏ của mình ──────────────
alter table public.cart_items enable row level security;

drop policy if exists "Giỏ hàng: chủ tài khoản được đọc" on public.cart_items;
create policy "Giỏ hàng: chủ tài khoản được đọc" on public.cart_items
  for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Giỏ hàng: chủ tài khoản được thêm" on public.cart_items;
create policy "Giỏ hàng: chủ tài khoản được thêm" on public.cart_items
  for insert to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Giỏ hàng: chủ tài khoản được sửa" on public.cart_items;
create policy "Giỏ hàng: chủ tài khoản được sửa" on public.cart_items
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Giỏ hàng: chủ tài khoản được xóa" on public.cart_items;
create policy "Giỏ hàng: chủ tài khoản được xóa" on public.cart_items
  for delete to authenticated
  using ((select auth.uid()) = user_id);

revoke all on public.cart_items from anon, authenticated;
grant select, insert, delete on public.cart_items to authenticated;
grant update (quantity) on public.cart_items to authenticated;

-- ── replace_cart: thay toàn bộ giỏ của người đang đăng nhập trong một transaction ──
-- Client gửi trạng thái giỏ đầy đủ sau mỗi thay đổi; hàm xóa dòng không còn,
-- UPSERT các dòng còn lại (trùng lựa chọn thì cộng dồn số lượng, tối đa 99).
-- SECURITY INVOKER: chạy với quyền của người gọi nên RLS vẫn áp dụng.
create or replace function public.replace_cart(items jsonb)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
begin
  if v_user is null then
    raise exception 'Bạn cần đăng nhập' using errcode = '42501';
  end if;
  if jsonb_typeof(coalesce(items, '[]'::jsonb)) <> 'array' then
    raise exception 'items phải là mảng' using errcode = '22023';
  end if;

  delete from public.cart_items where user_id = v_user;

  -- Gộp các dòng trùng lựa chọn trong dữ liệu gửi lên (cộng dồn số lượng) trước khi ghi.
  with parsed as (
    select
      (item ->> 'foodId')::bigint as food_id,
      nullif(item ->> 'sizeId', '')::bigint as size_id,
      coalesce(
        (select array_agg(distinct t::bigint order by t::bigint)
         from jsonb_array_elements_text(item -> 'toppingIds') as t),
        '{}'
      ) as topping_ids,
      coalesce((item ->> 'spiceLevel')::smallint, 0) as spice_level,
      (item ->> 'quantity')::integer as quantity
    from jsonb_array_elements(coalesce(items, '[]'::jsonb)) as item
  )
  insert into public.cart_items (user_id, food_id, size_id, topping_ids, spice_level, quantity)
  select v_user, food_id, size_id, topping_ids, spice_level, least(sum(quantity), 99)::integer
  from parsed
  group by food_id, size_id, topping_ids, spice_level
  -- Hai lần gọi chạy song song: lần ghi sau thắng.
  on conflict on constraint cart_items_line_unique
  do update set quantity = excluded.quantity;
end;
$$;

revoke execute on function public.replace_cart(jsonb) from public, anon;
grant execute on function public.replace_cart(jsonb) to authenticated;
