-- ── orders ──────────────────────────────────────────────────────────────────
create table if not exists public.orders (
  id              uuid primary key default gen_random_uuid(),
  code            text not null unique check (code ~ '^FD-[0-9]{6}-[0-9]{4,}$'),
  user_id         uuid not null references auth.users (id) on delete cascade,
  restaurant_id   bigint not null references public.restaurants (id),
  recipient_name  text not null check (length(trim(recipient_name)) between 2 and 100),
  phone           text not null check (phone ~ '^0[35789][0-9]{8}$'),
  address         text not null check (length(trim(address)) between 5 and 300),
  note            text not null default '' check (length(note) <= 300),
  payment_method  text not null default 'cod' check (payment_method = 'cod'),
  subtotal        integer not null check (subtotal >= 0),
  shipping_fee    integer not null check (shipping_fee >= 0),
  total           integer not null check (total = subtotal + shipping_fee),
  created_at      timestamptz not null default now(),
  cancelled_at    timestamptz check (cancelled_at is null or cancelled_at >= created_at)
);

comment on table public.orders is 'Đơn hàng. Chỉ tạo qua RPC place_order; trạng thái giao hàng suy ra từ created_at.';
comment on column public.orders.code is 'Mã đơn dễ đọc FD-YYMMDD-NNNN, đánh số lại mỗi ngày (giờ Việt Nam).';

create index if not exists orders_user_created_idx on public.orders (user_id, created_at desc);
create index if not exists orders_restaurant_id_idx on public.orders (restaurant_id);

-- ── order_items: bản chụp món tại thời điểm đặt ─────────────────────────────
-- Lưu tên và giá lúc đặt, nên sau này thực đơn đổi giá thì đơn cũ vẫn đúng.
create table if not exists public.order_items (
  id           bigint generated by default as identity primary key,
  order_id     uuid not null references public.orders (id) on delete cascade,
  food_id      bigint references public.foods (id) on delete set null,
  food_name    text not null,
  image_url    text,
  size_name    text,
  toppings     jsonb not null default '[]' check (jsonb_typeof(toppings) = 'array'),
  spice_level  smallint not null default 0 check (spice_level between 0 and 4),
  unit_price   integer not null check (unit_price >= 0),
  quantity     integer not null check (quantity between 1 and 99),
  line_total   integer not null check (line_total = unit_price * quantity)
);

comment on column public.order_items.toppings is 'Mảng [{ "id", "name", "price" }] tại thời điểm đặt.';

create index if not exists order_items_order_id_idx on public.order_items (order_id);
create index if not exists order_items_food_id_idx on public.order_items (food_id);

-- ── Bộ đếm mã đơn theo ngày ─────────────────────────────────────────────────
create table if not exists public.order_code_counters (
  day   date primary key,
  last  integer not null default 0
);
comment on table public.order_code_counters is 'Nội bộ: số thứ tự mã đơn trong ngày. Không ai truy cập qua API.';

-- ── Row Level Security ──────────────────────────────────────────────────────
alter table public.orders              enable row level security;
alter table public.order_items         enable row level security;
alter table public.order_code_counters enable row level security;

drop policy if exists "Đơn hàng: chủ tài khoản được đọc" on public.orders;
create policy "Đơn hàng: chủ tài khoản được đọc" on public.orders
  for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Món trong đơn: chủ đơn được đọc" on public.order_items;
create policy "Món trong đơn: chủ đơn được đọc" on public.order_items
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_items.order_id and o.user_id = (select auth.uid())
  ));

-- Chỉ đọc. Tạo đơn chỉ qua place_order; bộ đếm không mở cho ai.
revoke all on public.orders, public.order_items, public.order_code_counters from anon, authenticated;
grant select on public.orders, public.order_items to authenticated;

-- ── place_order ─────────────────────────────────────────────────────────────
-- items:    [{ foodId, sizeId, toppingIds, spiceLevel, quantity }]   (không có giá)
-- delivery: { recipientName, phone, address, note }
-- Trả về:   { id, code, total }
-- Lỗi (message):
--   not_authenticated · empty_cart · invalid_item · mixed_restaurants ·
--   invalid_delivery · below_minimum · out_of_stock
--   out_of_stock kèm detail = JSON [{ foodId, name, requested, available }].
--
-- SECURITY DEFINER vì cần trừ kho (bảng foods không cho client ghi). Hàm luôn
-- lấy người dùng từ auth.uid(), không nhận user id từ client.
create or replace function public.place_order(items jsonb, delivery jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  c_shipping_fee   constant integer := 15000;
  c_free_shipping  constant integer := 200000;
  c_min_subtotal   constant integer := 50000;

  v_user           uuid := auth.uid();
  v_restaurant     bigint;
  v_subtotal       integer;
  v_shipping       integer;
  v_order_id       uuid;
  v_code           text;
  v_day            date := (now() at time zone 'Asia/Ho_Chi_Minh')::date;
  v_seq            integer;
  v_name           text := trim(coalesce(delivery ->> 'recipientName', ''));
  v_phone          text := regexp_replace(coalesce(delivery ->> 'phone', ''), '[^0-9]', '', 'g');
  v_address        text := trim(coalesce(delivery ->> 'address', ''));
  v_note           text := trim(coalesce(delivery ->> 'note', ''));
  v_shortages      jsonb;
begin
  if v_user is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  if jsonb_typeof(items) is distinct from 'array' or jsonb_array_length(items) = 0 then
    raise exception 'empty_cart' using errcode = '22023';
  end if;

  if length(v_name) not between 2 and 100
     or v_phone !~ '^0[35789][0-9]{8}$'
     or length(v_address) not between 5 and 300
     or length(v_note) > 300 then
    raise exception 'invalid_delivery' using errcode = '22023';
  end if;

  -- 1. Đọc từng dòng; topping sắp xếp và bỏ trùng; số lượng 1–99.
  drop table if exists pg_temp._lines, pg_temp._priced;
  create temp table _lines on commit drop as
  select
    ord::integer                                     as line_no,
    (item ->> 'foodId')::bigint                      as food_id,
    nullif(item ->> 'sizeId', '')::bigint            as size_id,
    coalesce(
      (select array_agg(distinct t::bigint order by t::bigint)
       from jsonb_array_elements_text(coalesce(item -> 'toppingIds', '[]')) as t),
      '{}'::bigint[]
    )                                                as topping_ids,
    coalesce((item ->> 'spiceLevel')::smallint, 0)   as spice_level,
    (item ->> 'quantity')::integer                   as quantity
  from jsonb_array_elements(items) with ordinality as e(item, ord);

  if exists (select 1 from _lines where food_id is null or quantity is null or quantity not between 1 and 99) then
    raise exception 'invalid_item' using errcode = '22023';
  end if;

  -- 2. Khóa các món liên quan để hai đơn song song không cùng lấy phần cuối.
  perform 1 from public.foods
  where id in (select food_id from _lines)
  order by id
  for update;

  -- 3. Món phải tồn tại, đang bán; size và topping phải thuộc món; độ cay hợp lệ.
  --    Món có size mà không gửi size thì dùng size mặc định.
  update _lines l set size_id = (
    select s.id from public.food_sizes s
    where s.food_id = l.food_id
    order by s.is_default desc, s.sort_order, s.id
    limit 1
  )
  where l.size_id is null;

  if exists (
    select 1 from _lines l
    left join public.foods f on f.id = l.food_id and f.is_available
    where f.id is null
       or (l.size_id is not null and not exists (
             select 1 from public.food_sizes s where s.id = l.size_id and s.food_id = l.food_id))
       or (l.size_id is null and exists (
             select 1 from public.food_sizes s where s.food_id = l.food_id))
       or exists (
             select 1 from unnest(l.topping_ids) as t(id)
             where not exists (
               select 1 from public.food_toppings ft where ft.id = t.id and ft.food_id = l.food_id))
       or l.spice_level not between 0 and 4
       or (not f.has_spice and l.spice_level <> 0)
  ) then
    raise exception 'invalid_item' using errcode = '22023';
  end if;

  -- 4. Mọi món phải cùng một quán.
  select min(f.restaurant_id) into v_restaurant
  from _lines l join public.foods f on f.id = l.food_id;

  if (select count(distinct f.restaurant_id) from _lines l join public.foods f on f.id = l.food_id) > 1 then
    raise exception 'mixed_restaurants' using errcode = '22023';
  end if;

  -- 5. Tồn kho tính trên tổng mọi dòng của cùng một món.
  select jsonb_agg(jsonb_build_object(
           'foodId', f.id, 'name', f.name, 'requested', q.requested, 'available', f.stock)
         order by f.id)
  into v_shortages
  from (select food_id, sum(quantity)::integer as requested from _lines group by food_id) q
  join public.foods f on f.id = q.food_id
  where q.requested > f.stock;

  if v_shortages is not null then
    raise exception 'out_of_stock' using errcode = 'P0001', detail = v_shortages::text;
  end if;

  -- 6. Tự tính giá từ thực đơn: (giá gốc + phụ thu size + Σ topping) × số lượng.
  create temp table _priced on commit drop as
  select
    l.line_no, l.food_id, l.quantity, l.spice_level,
    f.name as food_name, f.image_url,
    s.name as size_name,
    coalesce((
      select jsonb_agg(jsonb_build_object('id', ft.id, 'name', ft.name, 'price', ft.price) order by ft.id)
      from public.food_toppings ft where ft.id = any (l.topping_ids)
    ), '[]'::jsonb) as toppings,
    f.base_price
      + coalesce(s.price_delta, 0)
      + coalesce((select sum(ft.price) from public.food_toppings ft where ft.id = any (l.topping_ids)), 0)
      as unit_price
  from _lines l
  join public.foods f on f.id = l.food_id
  left join public.food_sizes s on s.id = l.size_id;

  select sum(unit_price * quantity)::integer into v_subtotal from _priced;

  if v_subtotal < c_min_subtotal then
    raise exception 'below_minimum' using errcode = '22023',
      detail = json_build_object('subtotal', v_subtotal, 'minimum', c_min_subtotal)::text;
  end if;

  v_shipping := case when v_subtotal >= c_free_shipping then 0 else c_shipping_fee end;

  -- 7. Trừ kho.
  update public.foods f
  set stock = f.stock - q.requested
  from (select food_id, sum(quantity)::integer as requested from _lines group by food_id) q
  where f.id = q.food_id;

  -- 8. Sinh mã đơn theo ngày (giờ Việt Nam) và ghi đơn.
  insert into public.order_code_counters as c (day, last) values (v_day, 1)
  on conflict (day) do update set last = c.last + 1
  returning last into v_seq;

  v_code := 'FD-' || to_char(v_day, 'YYMMDD') || '-' || lpad(v_seq::text, 4, '0');

  insert into public.orders
    (code, user_id, restaurant_id, recipient_name, phone, address, note,
     subtotal, shipping_fee, total)
  values
    (v_code, v_user, v_restaurant, v_name, v_phone, v_address, v_note,
     v_subtotal, v_shipping, v_subtotal + v_shipping)
  returning id into v_order_id;

  insert into public.order_items
    (order_id, food_id, food_name, image_url, size_name, toppings, spice_level,
     unit_price, quantity, line_total)
  select v_order_id, food_id, food_name, image_url, size_name, toppings, spice_level,
         unit_price, quantity, unit_price * quantity
  from _priced
  order by line_no;

  -- 9. Dọn giỏ và nhớ thông tin giao hàng cho lần sau.
  delete from public.cart_items where user_id = v_user;

  update public.profiles
  set default_address = v_address,
      full_name = case when full_name = '' then v_name else full_name end,
      phone = case when phone = '' then v_phone else phone end
  where id = v_user;

  return jsonb_build_object('id', v_order_id, 'code', v_code, 'total', v_subtotal + v_shipping);
end;
$$;

revoke execute on function public.place_order(jsonb, jsonb) from public, anon;
grant execute on function public.place_order(jsonb, jsonb) to authenticated;
