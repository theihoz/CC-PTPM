// ── Trải phẳng thành các bảng ───────────────────────────────────────────────
export const foods = []
export const foodSizes = []
export const foodToppings = []

foodDefs.forEach((def, index) => {
  const { category, sizes = [], toppings = [], ...row } = def
  const id = index + 1
  foods.push({
    id,
    ...row,
    category_id: CAT[category],
    is_featured: row.is_featured ?? false,
    is_available: true,
    sort_order: index + 1,
  })
  sizes.forEach((size, i) => {
    foodSizes.push({
      id: foodSizes.length + 1,
      food_id: id,
      name: size.name,
      price_delta: size.price_delta,
      is_default: size.is_default ?? false,
      sort_order: i + 1,
    })
  })
  toppings.forEach((topping, i) => {
    foodToppings.push({
      id: foodToppings.length + 1,
      food_id: id,
      name: topping.name,
      price: topping.price,
      sort_order: i + 1,
    })
  })
})

/** Ghép các bảng thành đúng hình dạng mà Supabase trả về cho truy vấn lồng nhau. */
export function nestedMenuRows() {
  return {
    categories: categories.map((c) => ({ ...c })),
    restaurants: restaurants.map((r) => ({
      ...r,
      open_time: `${r.open_time}:00`,
      close_time: `${r.close_time}:00`,
      foods: foods
        .filter((f) => f.restaurant_id === r.id && f.is_available)
        .map((f) => ({
          ...f,
          food_sizes: foodSizes.filter((s) => s.food_id === f.id),
          food_toppings: foodToppings.filter((t) => t.food_id === f.id),
        })),
    })),
  }
}
